import { ArmDefinition, ArmSpecs } from '../arms/types';
import { ARM_LIMITATIONS_DATA } from './limitations';

export function generateSpecsMarkdown(armDef: ArmDefinition, params: Record<string, number>): string {
  const specs: ArmSpecs = armDef.specs(params);
  const limitations = ARM_LIMITATIONS_DATA[armDef.id];

  return `# ${specs.name} Specification Sheet

## 1. General Specifications
- **Degrees of Freedom (DOF):** ${specs.dof}
- **Joint Kinematic Sequence:** \`${specs.jointSequence}\`
- **Workspace Envelope Shape:** ${specs.workspaceShape}
- **Estimated Reachable Volume:** ${specs.approxVolume.toFixed(3)} m³
- **Maximum Reach:** ${specs.maxReach.toFixed(3)} m
- **Minimum Reach / Dead Zone:** ${specs.minReach.toFixed(3)} m
- **Installation Footprint:** ${specs.footprint}
- **Total Overhead Height:** ${specs.totalHeight}

## 2. Joint Specifications
| Joint | Name | Type | Axis | Range (Min / Max) | Units |
|---|---|---|---|---|---|
${armDef.joints
  .map(
    (j) =>
      `| ${j.id.toUpperCase()} | ${j.name} | ${j.type === 'R' ? 'Revolute (Rotary)' : 'Prismatic (Linear)'} | ${j.axis.toUpperCase()} | [${j.min}, ${j.max}] | ${j.unit} |`
  )
  .join('\n')}

## 3. Reference Dynamic & Mechanical Ratings (Typical)
- **Rated Payload:** ${specs.typicalPayloadKg} kg
- **Repeatability (ISO 9283):** ±${specs.repeatabilityMm} mm
- **Max Tool Center Point (TCP) Speed:** ${specs.maxToolSpeedMs} m/s
- **Number of Distinct IK Solution Branches:** ${specs.ikSolutionCount}

## 4. Kinematic Singularities & Boundary Conditions
${specs.singularityConditions.map((s) => `- ${s}`).join('\n')}

## 5. Architectural Limitations & Operating Advice
### Inherent Limitations
${limitations?.inherentLimitations.map((l) => `- ${l}`).join('\n') ?? '- None listed'}

### Practical Operating Recommendations
${limitations?.practicalTips.map((t) => `- ${t}`).join('\n') ?? '- Standard industrial safety protocols'}

### Recommended Industrial Use Cases
${limitations?.bestSuitedFor.map((u) => `- ${u}`).join('\n') ?? '- General automation'}

---
*Generated by RoboKin 3-DOF Kinematics Simulator*
`;
}

export function generateSpecsJSON(armDef: ArmDefinition, params: Record<string, number>): string {
  const specs: ArmSpecs = armDef.specs(params);
  const limitations = ARM_LIMITATIONS_DATA[armDef.id];

  const payload = {
    specs,
    joints: armDef.joints,
    parameters: params,
    limitations,
    exportTimestamp: new Date().toISOString()
  };

  return JSON.stringify(payload, null, 2);
}
